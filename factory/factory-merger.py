MARK = "<!-- factory-merger"
FILE = "factory.yml"
RED_LABEL = "factory: main red"
CLAIM_LABEL = "crew: in progress"   # Issue Radar's claim; the forge leaves it on a closed issue
MERGED_TAG = f"{MARK} merged -->"
ADOPT_TAG = f"{MARK} adopt -->"
REFRESH_TAG = f"{MARK} adopt-refresh -->"
NOT_YET = "not yet"
STUCK_HOURS = 2     # after a refresh, this long without a pipeline newer than the adoption: say so


def note_once(forge, mr, reason: str, body: str) -> bool:
    """Post `body` once per (head SHA, reason). True when it was posted now."""
    tag = f"{MARK} sha={mr.head} reason={reason[:40]} -->"
    try:
        if any(tag in c.body for c in forge.comments(mr)):
            return False
        forge.comment(mr, f"{body}\n\n{tag}")
    except ForgeError:
        return True  # report it this tick; the comment is tried again on the next one
    return True


def note_ignored(forge, mr, cfg: Config, ignored: list[str]) -> bool:
    """Say once, for each set of labels, that a `scope.label` someone outside `humans` added does not count."""
    tag = f"{MARK} scope-ignored {'; '.join(ignored)} -->"
    try:
        if any(tag in c.body for c in forge.comments(mr)):
            return False
        forge.comment(mr, f"Merger: the label `{cfg.scope_label}` {', '.join(ignored)} was not added by a "
                          "person in `humans`, so the factory does not take this merge request on. To bring "
                          "it in, a person in `humans` removes the label and puts it on again.\n\n" + tag)
    except ForgeError:
        return False  # tried again on the next tick
    return True


TIER_IGNORED_RE = re.compile(r"#(\d+) has (\S+) from `([^`]*)`, " + re.escape(TIER_IGNORED))


def note_tier_ignored(forge, mr, note: str) -> bool:
    """Say once, per issue, tier and account, that a tier label set by someone outside `humans`
    and the triager does not count (the issue stays at the highest tier). True when posted now."""
    found = TIER_IGNORED_RE.search(note or "")
    if not found:
        return False
    issue, tier, who = found.groups()
    tag = f"{MARK} tier-ignored #{issue} {tier} {who} -->"
    try:
        if any(tag in c.body for c in forge.comments(mr)):
            return False
        forge.comment(mr, f"Merger: the tier `{tier}` on #{issue} was set by `{who}`, who is neither in "
                          "`humans` nor the `triager` in factory.yml, so it does not count: the issue is "
                          "read as the highest tier. A person in `humans`, or the triager, sets the tier "
                          f"again.\n\n{tag}")
    except ForgeError:
        return False  # tried again on the next tick
    return True


def close_fixed(forge, mr, cfg: Config):
    word = f"{forge.mr_ref}{mr.number}"
    for n in forge.closing_issues(mr):
        if not forge.issue_is_open(n):
            continue
        forge.comment_issue(n, f"Merger: done in `{mr.target}` by {word}. It reaches "
                               f"`{cfg.default_branch}` with the whole feature.\n\n{MARK} closed -->")
        forge.close_issue(n)


def after_merge(forge, mr, note: str):
    """The merge comment (once per merge request) and the claim label off its closing issues."""
    if not any(MERGED_TAG in c.body for c in forge.comments(mr)):
        forge.comment(mr, f"Merger: merged `{mr.head[:8]}` into `{mr.target}`. {note}.\n\n{MERGED_TAG}")
    for n in forge.closing_issues(mr):
        if CLAIM_LABEL in forge.issue(n).labels:
            forge.remove_issue_label(n, CLAIM_LABEL)


def red_body(branch: str, failing: list[str], where: str) -> str:
    jobs = ", ".join(f"`{j}`" for j in failing) or "(the pipeline failed; no single job named)"
    return (f"The latest result on `{branch}` is red ({where}). Failing: {jobs}.\n\n"
            f"The merger holds every merge into `{branch}` until it is green again, then closes this "
            "issue. Fix this first. A merge request whose own checks fail only because of this does "
            f"not need its own fix; a person merges the fix of `{branch}` by hand when the merger "
            f"holds it too.\n\n{MARK} main-red -->")


def watch_main(forge, cfg: Config, out: dict) -> int | None:
    """The open `factory: main red` issue while the default branch is red, else None.

    Red: open the issue, or update its body when the failing jobs changed. Green: close it.
    Pending or unknown: keep what is there, so a hold lasts until a green result. A forge read
    that fails is reported and holds nothing (the merger then works as without this watch).
    """
    branch = cfg.default_branch
    try:
        state, failing, where = forge.branch_status(branch)
        found = forge.find_issues(RED_LABEL)
        issue = found[0] if found else None
        if state == "red":
            body = red_body(branch, failing, where)
            if issue is None:
                issue = forge.create_issue(f"factory: {branch} is red", body, [RED_LABEL])
                out["main"] = f"{branch} red ({', '.join(failing) or where}): opened #{issue}, holding merges"
            elif forge.issue(issue).body != body:
                forge.update_issue(issue, body)
                out["main"] = f"{branch} still red ({', '.join(failing) or where}): updated #{issue}"
            return issue
        if state == "green" and issue is not None:
            forge.comment_issue(issue, f"Merger: `{branch}` is green again ({where}). Merging resumes."
                                       f"\n\n{MARK} main-green -->")
            forge.close_issue(issue)
            out["main"] = f"{branch} green again: closed #{issue}, merging resumes"
            return None
        return issue
    except ForgeError as e:
        out["errors"].append(f"{branch}: could not read its status or the {RED_LABEL!r} issue ({e})")
        return None


def note_held(forge, mr, issue: int, branch: str) -> bool:
    """One comment per merge request and red issue. True when it was posted now."""
    tag = f"{MARK} main-red issue={issue} -->"
    try:
        if any(tag in c.body for c in forge.comments(mr)):
            return False
        forge.comment(mr, f"Merger: holding. `{branch}` is red (#{issue}); this merge request waits "
                          f"until it is green again. Nothing to fix here unless its own change "
                          f"broke it.\n\n{tag}")
    except ForgeError:
        return True
    return True


def adoption(mr, comments, cfg: Config, now: datetime.datetime):
    """(state, since) of an adopted merge request, from its comments.

    announce: no adoption comment yet. wait: less than `scope.adopt_wait_hours` since it and no
    reply from the author. stopped: the author's latest reply after it says "not yet". refresh:
    the wait is over (or the author replied) and the branch was not brought up to date yet.
    ready: it was; `since` is the adoption comment's time, and only checks newer than it count.
    The adoption comment is the first one with the marker that the author did not write.
    """
    marks = [c for c in comments if ADOPT_TAG in c.body and c.author != mr.author]
    if not marks:
        return "announce", None
    since = ts(marks[0].created_at)
    if since is None:
        return "wait", None  # a comment without a time is never the start of a merge
    replies = [c for c in comments if c.author == mr.author and (ts(c.created_at) or since) > since]
    if replies and NOT_YET in replies[-1].body.lower():
        return "stopped", since
    if not replies and now - since < datetime.timedelta(hours=cfg.adopt_wait_hours):
        return "wait", since
    if not any(REFRESH_TAG in c.body and c.author != mr.author for c in comments):
        return "refresh", since
    return "ready", since


def adopt_body(mr, cfg: Config) -> str:
    n = cfg.adopt_wait_hours
    hours = f"{n:g} hour" + ("" if n == 1 else "s")
    return (f"Merger: @{mr.author}, this merge request is labelled `{cfg.scope_label}`, so the factory "
            f"takes it on. In {hours}, or as soon as you reply here, it brings the branch up to "
            f"date with `{cfg.default_branch}` and merges it when the new pipeline passes the rules of "
            "its tier (the repository's checks, the tier, the docs check and both AI reviews). A "
            "pipeline from before this comment does not count. To stop it, reply \"not yet\" or "
            f"remove the label `{cfg.scope_label}`.\n\n{ADOPT_TAG}")


def merge_pass(forge, now: datetime.datetime | None = None) -> dict:
    """One tick. Returns {"merged": [...], "rebased": [...], "refused": [...], "error": str|None}."""
    now = now or datetime.datetime.now(datetime.timezone.utc)
    out = {"merged": [], "rebased": [], "refused": [], "held": [], "adopted": [], "ignored": [], "tier_ignored": [],
           "errors": [],
           "error": None}
    default = forge.default_branch()
    text = forge.read_file(FILE, default)
    if text is None:
        out["quiet"] = True  # not configured yet (the configure MR is not merged): stay quiet
        return out
    try:
        base = parse_config(text)
    except ConfigError as e:
        out["error"] = f"{FILE} on {default} is invalid: {e}"
        return out
    if base.default_branch != default:
        out["error"] = f"{FILE} says default_branch {base.default_branch!r} but the forge says {default!r}"
        return out
    if base.forge_kind != forge.kind:
        out["error"] = f"{FILE} says forge {base.forge_kind!r} but the merger runs against {forge.kind!r}"
        return out
    forge.merge_method = base.merge_method
    mrs, adopted = [], {}
    for m in forge.open_mrs():
        if not (m.target == default or base.is_feature(m.target)):
            continue
        # Own mode: a merge request outside the factory's stream is not read further, merged,
        # rebased, commented on or reported. Full mode answers without a forge call.
        try:
            ok, _why, ignored = scope_decision(forge, m, base)
            if not ok:
                if ignored and note_ignored(forge, m, base, ignored):
                    out["ignored"].append(f"{forge.mr_ref}{m.number}")
                continue
            if is_adopted(forge, m, base):
                adopted[m.number] = forge.comments(m)
        except ForgeError as e:
            out["errors"].append(f"{forge.mr_ref}{m.number}: could not read its scope ({e})")
            continue
        mrs.append(m)
    today = sum(1 for cs in adopted.values() for c in cs if ADOPT_TAG in c.body
                and (ts(c.created_at) or now).date() == now.date() and (ts(c.created_at) or now) <= now)
    cfgs: dict[str, Config | None] = {default: base}
    for t in {m.target for m in mrs} - {default}:
        if not forge.branch_exists(t):
            cfgs[t] = None  # MRs into a deleted branch stay listed on GitLab: skip them
            continue
        try:
            own = forge.read_file(FILE, t)
            cfgs[t] = feature_config(base, parse_config(own) if own else None)
        except ConfigError as e:
            cfgs[t] = None
            out["refused"].append(f"{t}: {FILE} is invalid ({e})")
    red = watch_main(forge, base, out)
    behind, busy, refresh = [], False, []
    for mr in mrs:
        cfg = cfgs.get(mr.target)
        if cfg is None:
            continue
        ref = f"{forge.mr_ref}{mr.number}"
        since = None
        if mr.number in adopted:
            comments = adopted[mr.number]
            state, since = adoption(mr, comments, base, now)
            if state == "announce":
                if mr.draft or HOLD_LABELS & set(mr.labels) or red is not None or today >= base.adopt_per_day:
                    continue  # adopted later: a person's draft, a hold, a red main or today's cap
                try:
                    forge.comment(mr, adopt_body(mr, base))
                except ForgeError as e:
                    out["errors"].append(f"{ref}: could not post the adoption comment ({e})")
                    continue
                today += 1
                out["adopted"].append(ref)
                continue
            if state in ("wait", "stopped"):
                continue
            if state == "refresh":
                if not mr.draft and not HOLD_LABELS & set(mr.labels) and red is None:
                    refresh.append(mr)
                continue
        if red is not None and mr.target == default:
            if not mr.draft and note_held(forge, mr, red, default):
                out["held"].append(ref)
            continue
        try:
            reason, note = check_mr(forge, mr, cfg, since)
        except ForgeError as e:  # a rule never decides on a partial read: try again next tick
            out["errors"].append(f"{ref}: could not read it ({e})")
            continue
        if reason != WAIT and note_tier_ignored(forge, mr, note):
            out["tier_ignored"].append(ref)
        if reason == STALE:
            # Refreshed, but no pipeline newer than the adoption yet. Say so once if it lasts.
            done = [ts(c.created_at) for c in adopted.get(mr.number, []) if REFRESH_TAG in c.body]
            if done and done[0] and now - done[0] > datetime.timedelta(hours=STUCK_HOURS):
                reason = ("no pipeline ran after the adoption comment: push to the branch or run its "
                          "pipeline again")
                if note_once(forge, mr, reason, f"Merger: not merged at `{mr.head[:8]}`: {reason}."):
                    out["refused"].append(f"{ref}: {reason}")
            continue
        if reason == WAIT:
            busy = True  # a pipeline is running: it may end in a merge that moves the target
            continue
        if reason is None and mr.mergeable == "checking":
            continue
        if reason is None and mr.mergeable == "conflict":
            reason = "has conflicts with the target branch: resolve them and push"
        if reason is None and mr.mergeable == "behind":
            behind.append(mr)
            continue
        if reason is None:
            try:
                forge.merge(mr)
                out["merged"].append(f"{ref}@{mr.head[:8]}" + (f" ({note})" if "overridden" in note else ""))
                if mr.target != default:
                    try:
                        close_fixed(forge, mr, cfg)
                    except ForgeError as e:
                        out["errors"].append(f"{ref}: merged, but closing its issues failed ({e})")
                try:
                    after_merge(forge, mr, note)
                except ForgeError as e:
                    out["errors"].append(f"{ref}: merged, but its merge comment or claim label failed ({e})")
                continue
            except ForgeError as e:
                reason = f"merge refused by the forge: {e}"
        if note_once(forge, mr, reason, f"Merger: not merged at `{mr.head[:8]}`: {reason}."):
            out["refused"].append(f"{ref}: {reason}")
    # One rebase at a time, and only while nothing runs and nothing merged this tick: either can
    # move the target again and waste the rebase (each one re-runs the whole pipeline). An
    # adopted merge request whose wait is over goes first, once.
    if refresh and not busy and not out["merged"]:
        mr = refresh[0]
        ref = f"{forge.mr_ref}{mr.number}"
        try:
            forge.comment(mr, f"Merger: bringing `{mr.head[:8]}` up to date with `{mr.target}` for the "
                              "adoption. The new pipeline runs every check; the merge request merges "
                              f"when it passes the rules of its tier.\n\n{REFRESH_TAG}")
            what = forge.refresh(mr)
            out["rebased"].append(f"{ref}@{mr.head[:8]} (adopted: {what})")
        except ForgeError as e:
            reason = f"could not bring the branch up to date for the adoption ({e}); rebase it by hand"
            if note_once(forge, mr, reason, f"Merger: not merged at `{mr.head[:8]}`: {reason}."):
                out["refused"].append(f"{ref}: {reason}")
    elif behind and not busy and not out["merged"]:
        mr = behind[0]
        ref = f"{forge.mr_ref}{mr.number}"
        if not forge.rebase_in_progress(mr):
            # The rebase note is per head: a second one for the same head means the last rebase
            # did not take (it would have produced a new head), so ask a person instead.
            if note_once(forge, mr, "rebase", f"Merger: `{mr.head[:8]}` is behind `{mr.target}`. "
                         "Updating it; the new commit runs its own checks and is merged when green."):
                try:
                    forge.rebase(mr)
                    out["rebased"].append(f"{ref}@{mr.head[:8]}")
                except ForgeError as e:
                    reason = f"rebase refused by the forge ({e}); rebase the branch by hand"
                    if note_once(forge, mr, reason, f"Merger: not merged at `{mr.head[:8]}`: {reason}."):
                        out["refused"].append(f"{ref}: {reason}")
            else:
                reason = "rebase did not complete; rebase the branch by hand"
                if note_once(forge, mr, reason, f"Merger: not merged at `{mr.head[:8]}`: {reason}."):
                    out["refused"].append(f"{ref}: {reason}")
    return out


def summary(out: dict) -> str:
    if out.get("error"):
        return f"merger: {out['error']}"
    return ("merger: merged " + (", ".join(out["merged"]) or "none")
            + ("; " + out["main"] if out.get("main") else "")
            + ("; adopted " + ", ".join(out["adopted"]) if out.get("adopted") else "")
            + ("; held " + ", ".join(out["held"]) if out.get("held") else "")
            + ("; scope label ignored on " + ", ".join(out["ignored"]) if out.get("ignored") else "")
            + ("; tier label ignored on " + ", ".join(out["tier_ignored"]) if out.get("tier_ignored") else "")
            + ("; rebased " + ", ".join(out["rebased"]) if out["rebased"] else "")
            + ("; refused " + "; ".join(out["refused"]) if out["refused"] else "")
            + ("; errors " + "; ".join(out["errors"]) if out.get("errors") else ""))


def actions(out: dict) -> list[str]:
    """What a tick did, one line each. Empty when there was nothing to do."""
    return ([f"merged {x}" for x in out["merged"]] + [f"rebased {x}" for x in out["rebased"]]
            + [f"refused {x}" for x in out["refused"]] + [f"held {x}" for x in out.get("held", [])]
            + [f"adopted {x}" for x in out.get("adopted", [])]
            + [f"scope label ignored on {x}" for x in out.get("ignored", [])]
            + [f"tier label ignored on {x}" for x in out.get("tier_ignored", [])]
            + ([out["main"]] if out.get("main") else []))


def run(ctx):
    """The Kiro Crew script cron entry (installs without Issue Radar EE)."""
    msg = json.loads(ctx.message)
    token = os.environ.get(msg.get("token_env") or "FACTORY_MERGER_TOKEN", "")
    if not token:
        raise Skip()  # secret not approved yet: Schedule shows the request; stay quiet
    forge = make_forge(msg["forge"], msg["url"], msg["project"], token)
    out = merge_pass(forge)
    if out.get("error") or out["errors"] or actions(out):
        raise Report(summary(out))
    raise Skip()


def main(argv: list[str] | None = None) -> int:
    """The command-line entry: one tick, as an Issue Radar EE step of kind `command` runs it
    from a checkout of the default branch:

      python3 -I factory/factory-merger.py --once --forge gitlab --url https://gitlab.example \\
          --project group/repo --token-env FACTORY_MERGER_TOKEN

    The token is read only from the variable `--token-env` names, never from an argument.
    The URL must be https (plain http only to the loopback). The last stdout line is JSON,
    {"summary": str, "actions": [str]}, also on an error. Exit 0 when the tick ran (merged,
    refused or found nothing to do); 1 when the forge could not be read or answered something
    unexpected, or factory.yml is invalid; 2 on a usage error, a missing token or a missing
    PyYAML.
    """
    import argparse
    import http.client

    def fail(code: int, text: str) -> int:
        print(json.dumps({"summary": f"merger: {text}", "actions": []}))
        return code

    p = argparse.ArgumentParser(prog="factory-merger.py",
                                description="Factory merger: one tick against one repository.",
                                allow_abbrev=False)  # `--token x` must not pass as `--token-env x`
    p.add_argument("--once", action="store_true", required=True, help="run one tick and exit")
    p.add_argument("--forge", required=True, choices=["gitlab", "github"])
    p.add_argument("--url", required=True, help="the forge's web URL, e.g. https://gitlab.example")
    p.add_argument("--project", required=True, help="GitLab project path or GitHub owner/name")
    p.add_argument("--token-env", default="FACTORY_MERGER_TOKEN",
                   help="name of the environment variable holding the merger's token")
    a = p.parse_args(argv)
    token = os.environ.get(a.token_env, "")
    if not token:
        print(f"factory-merger: the variable {a.token_env} is empty or not set", file=sys.stderr)
        return fail(2, f"the variable {a.token_env} is empty or not set")
    try:
        import yaml  # noqa: F401, PLC0415 - factory.yml needs it; say so before reading the forge
    except ImportError:
        return fail(2, "pyyaml missing: install it for this python3 (python3-yaml or a system "
                       "`pip install pyyaml`; under -I the user site is not on the path)")
    try:
        out = merge_pass(make_forge(a.forge, a.url, a.project, token))
    except (ForgeError, OSError, http.client.HTTPException) as e:  # OSError: urllib's network errors
        return fail(1, f"could not read the forge ({e})")
    except (ValueError, KeyError, TypeError) as e:  # a bad URL, or an answer that is not the API's
        return fail(1, f"could not read the forge ({type(e).__name__}: {e})")
    print(json.dumps({"summary": summary(out), "actions": actions(out)}))
    return 1 if out.get("error") or out["errors"] else 0


if __name__ == "__main__":
    sys.exit(main())
