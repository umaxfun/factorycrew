"""Factory merger: a deterministic Kiro Crew script cron. No model is called.

Register `merger/factory-merger.py:run` (the one-file build of this module plus
factory/fcore.py and factory/forges.py, made by merger/bundle.py) as a script cron every
60 s, and grant it the vault secret with the merger's forge token. The grant is pinned to
that file's exact content, which is why the merger ships as one file.

Configure also commits the same file to the repository as `factory/factory-merger.py`. With
Issue Radar EE it runs from there, from a checkout of the default branch, by its command-line
entry (`main`, `--once --forge ... --url ... --project ... --token-env ...`), instead of the cron.

The cron `message` is a JSON object with the forge address only; every rule comes from
factory.yml on the repository's default branch:

  {"forge": "gitlab", "url": "https://gitlab.example", "project": "group/repo",
   "token_env": "FACTORY_MERGER_TOKEN"}

An open MR into the default branch, or into a feature branch matching `designs.branches`,
is merged at its head SHA only when `fcore.check_mr` finds nothing against it: not a draft,
no hold label, every check finished on the head, every check its tier requires succeeded
(an AI review may instead be cleared by a person's `/factory override ai-review <sha> <class>
[model=<model>]: <reason>` comment for that head, or by the crew's own `false-positive`
override when the review's anchors allow it), no other check failed, no open thread, a screenshot when
`evidence.screenshot_when` matches, a person's approval for a gate path, for a tier with
`automerge: false`, and for a feature branch going into the default branch.

For a feature branch target the rules are the default branch's, made stricter (never
looser) by the feature branch's own factory.yml; after a merge into a feature branch the
merger closes the MR's `Fixes #N` issues itself, because the forge closes them only on the
default branch.

Before any merge it reads the default branch's latest result. Red: it opens (or updates) one
issue labelled `factory: main red` with the failing jobs, merges nothing into the default
branch and says so once on each waiting MR; green again: it closes the issue and resumes.

After each merge it says so once on the merge request (marker `merged`): the head, the target
and why it was allowed (tier, overrides). It also takes the crew's claim label
`crew: in progress` off the issues the merge request closes, which nobody else removes.

A branch behind its target is rebased (GitLab) or updated (GitHub), one at a time and only
while no pipeline runs; a branch with conflicts is handed to a person. Each refusal is one
comment per (head SHA, reason).

`scope.mode: own` limits all of this to the factory's own stream (`fcore.in_scope`): a merge
request into the default branch counts only when it carries `scope.label` or closes an issue
that carries it, each added by a person in `humans`; one into a feature branch always counts.
Any other merge request is not merged, rebased, commented on or reported, except one comment
when a `scope.label` on it or its issue was added by someone else (marker `scope-ignored`).
The red-main watch is unchanged.

An issue's tier below the highest counts only when a person in `humans` or the `triager` set it
(`fcore.issue_tier`); from anyone else the issue is the highest tier, and the merger says so once
per issue, tier and account (marker `tier-ignored`).

An **adopted** merge request (`fcore.is_adopted`: in scope only through its own label, so a
person's, not the crew's) goes through, in order: one comment to its author (marker
`adopt`, at most `scope.adopt_per_day` of them per UTC day, none while the default branch is
red or the merge request is a draft or held); a wait of `scope.adopt_wait_hours`, ended early
by any reply of the author; one refresh (rebase or update when behind, else a new pipeline on
the head, marker `adopt-refresh`); then the usual rules, but only on checks that ran after the
adoption comment. The author's latest reply saying "not yet" stops it until a later reply that
does not; removing the label takes it out of scope.
"""

